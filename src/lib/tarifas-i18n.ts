const STORAGE = 'ts-tarifas-lang';

export function readTarifasLocale(): TarifasLocale {
  if (typeof window === 'undefined') return 'es';
  const raw = window.localStorage.getItem(STORAGE);
  if (raw === 'es' || raw === 'pt' || raw === 'it' || raw === 'fr') return raw;
  return 'es';
}

export function writeTarifasLocale(locale: TarifasLocale) {
  if (typeof window === 'undefined') return;
  window.localStorage.setItem(STORAGE, locale);
}

